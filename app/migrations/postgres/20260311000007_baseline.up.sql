CREATE TABLE messages (
  messageid           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created             timestamptz  NOT NULL DEFAULT now(),
  lastaccessed        timestamptz  NOT NULL DEFAULT now(), -- MySQL `lastAccessed` ON UPDATE; no reader, no trigger
  viewed              integer      DEFAULT 0,
  firstname           varchar(100),
  lastname            varchar(100),
  other_firstname     varchar(100),
  other_lastname      varchar(100),
  message             text         NOT NULL,
  email               varchar(255),
  other_email         varchar(255),
  uniqueid            varchar(255) CONSTRAINT messages_uniqueid_key UNIQUE,
  is_client_encrypted boolean      NOT NULL DEFAULT false,
  view_count          integer      NOT NULL DEFAULT 0,
  max_view_count      integer      NOT NULL DEFAULT 5,
  expires_at          timestamptz  NOT NULL DEFAULT (now() + interval '7 days')
);
CREATE INDEX idx_messages_view_count      ON messages (view_count);
CREATE INDEX idx_messages_max_view_count  ON messages (max_view_count);
CREATE INDEX idx_messages_expires_at      ON messages (expires_at);
CREATE INDEX idx_messages_reminder_lookup ON messages (view_count, created, other_email);
COMMENT ON COLUMN messages.max_view_count IS 'Maximum number of times this message can be viewed before deletion';
COMMENT ON COLUMN messages.expires_at     IS 'Expires 7 days after creation';

CREATE TABLE email_reminders (
  id                 integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  message_id         integer      NOT NULL REFERENCES messages (messageid) ON DELETE CASCADE,
  email_address      varchar(255) NOT NULL,
  reminder_count     integer      DEFAULT 0,
  last_reminder_sent timestamptz  DEFAULT now(),
  created_at         timestamptz  DEFAULT now(),
  CONSTRAINT uq_email_reminders_message_email UNIQUE (message_id, email_address)
);
CREATE INDEX idx_email_reminders_email_address      ON email_reminders (email_address);
CREATE INDEX idx_email_reminders_last_reminder_sent ON email_reminders (last_reminder_sent);

CREATE TABLE file_upload_sessions (
  session_id      varchar(255) PRIMARY KEY,
  file_id         varchar(255) NOT NULL CONSTRAINT uq_file_id UNIQUE,
  message_id      varchar(255) NOT NULL DEFAULT '',
  upload_id       varchar(255) NOT NULL DEFAULT '',
  filename        varchar(255) NOT NULL DEFAULT '',
  content_type    varchar(255) NOT NULL DEFAULT '',
  total_size      bigint       NOT NULL DEFAULT 0,
  total_chunks    integer      NOT NULL DEFAULT 0,
  status          varchar(50)  NOT NULL DEFAULT 'active',
  encryption_key  bytea,
  completed_parts jsonb        NOT NULL,
  created_at      timestamptz  NOT NULL DEFAULT now(),
  expires_at      timestamptz  NOT NULL DEFAULT now()
);
CREATE INDEX idx_file_upload_sessions_expires_at        ON file_upload_sessions (expires_at);
CREATE INDEX idx_file_upload_sessions_status_expires_at ON file_upload_sessions (status, expires_at);
COMMENT ON TABLE file_upload_sessions IS 'Upload session metadata for chunked encrypted file uploads';
